let language = "ko";

function interpolate(text, params) {
  return text.replace(/\{(\w+)\}/g, (match, key) => (params[key] ?? match));
}

export function getLanguage() {
  return language;
}

export function t(key, params = {}) {
  const text = STRINGS[language]?.[key] ?? STRINGS.ko[key] ?? key;
  return interpolate(text, params);
}

export function applyStatic(root = document) {
  document.documentElement.lang = language;
  document.title = t("app.title");
  for (const element of root.querySelectorAll("[data-i18n]")) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll("[data-i18n-placeholder]")) element.placeholder = t(element.dataset.i18nPlaceholder);
  for (const element of root.querySelectorAll("[data-i18n-title]")) {
    const text = t(element.dataset.i18nTitle);
    element.title = text;
    element.setAttribute("aria-label", text);
  }
}

export function setLanguage(next) {
  language = next === "en" ? "en" : "ko";
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Language preference is optional.
  }
  applyStatic();
  return language;
}

export function initLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch {
    // Keep the default language.
  }
  language = stored === "en" ? "en" : "ko";
  applyStatic();
  return language;
}
